from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", default="results")
    return parser.parse_args()


def load_runs(runs_dir: Path) -> pd.DataFrame:
    records = [json.loads(p.read_text()) for p in sorted(runs_dir.glob("*.json"))]
    if not records:
        raise SystemExit(
            f"No run records found under {runs_dir}. Run scripts/evaluate.py first."
        )
    return pd.DataFrame.from_records(records)


def main() -> None:
    args = parse_args()
    results_dir = Path(args.results_dir)
    df = load_runs(results_dir / "runs")

    # Keep only the best (by linear-probe accuracy) run per model, so this table
    # reports each architecture's best checkpoint, not every evaluation attempt.
    df = df.sort_values("linear_probe_accuracy", ascending=False)
    best_per_model = df.drop_duplicates(subset="model", keep="first")
    best_per_model = best_per_model.sort_values("linear_probe_accuracy", ascending=False)

    table_columns = [
        "model",
        "num_params",
        "embedding_dim",
        "linear_probe_accuracy",
        "knn_accuracy",
        "n_test",
        "checkpoint",
        "timestamp",
    ]
    table = best_per_model[table_columns].rename(
        columns={
            "model": "Method",
            "num_params": "Params",
            "embedding_dim": "Embed dim",
            "linear_probe_accuracy": "Linear probe acc.",
            "knn_accuracy": "kNN acc.",
            "n_test": "# test images",
            "checkpoint": "Checkpoint",
            "timestamp": "Evaluated at (UTC)",
        }
    )
    table["Linear probe acc."] = table["Linear probe acc."].map("{:.3f}".format)
    table["kNN acc."] = table["kNN acc."].map("{:.3f}".format)

    out_path = results_dir / "RESULTS.md"
    header = (
        "# LITHOS self-supervised pretraining -- results\n\n"
        "Auto-generated by `scripts/aggregate_results.py` from `results/runs/*.json`. "
        "Do not hand-edit -- re-run the script instead.\n\n"
        "Both accuracy columns are measured on the held-out, section-level test split "
        "(see `src/lithos_ssl/data/splits.py`): `Linear probe acc.` fits a logistic-"
        "regression classifier on frozen embeddings, `kNN acc.` is a k=20 cosine "
        "nearest-neighbour vote with no extra training. See "
        "`src/lithos_ssl/eval/linear_probe.py` and `knn.py`.\n\n"
    )
    out_path.write_text(header + table.to_markdown(index=False))
    print(f"Wrote {out_path} ({len(table)} rows).")


if __name__ == "__main__":
    main()
